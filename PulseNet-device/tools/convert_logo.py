"""Convert the HCMUTE logo PNG to an RGB565 C array for the
ST7735 160x128 display.

Idle screen style: WHITE background, HCMUTE-purple logo
(the source file is a white stroke; its alpha channel is
recolored to purple), full-screen.

Usage: py -3 tools/convert_logo.py
"""

from PIL import Image

SRC = "assets/logo_hcmute_official.png"
DST = "src/logo.h"

W, H = 160, 128

BG = (255, 255, 255)       # white background
STROKE = (92, 31, 116)     # HCMUTE purple logo

img = Image.open(SRC).convert("RGBA")

# Scale the logo to fit within the screen, keeping aspect.
scale_w = int(W * 0.78)
scale_h = int(H * 0.74)

img.thumbnail((scale_w, scale_h), Image.LANCZOS)

# Recolor the white stroke to purple, keeping the alpha
# channel (anti-aliasing) intact.
alpha = img.split()[3]

solid = Image.new("RGBA", img.size, STROKE + (255,))
solid.putalpha(alpha)

canvas = Image.new("RGB", (W, H), BG)

# Place slightly above center: the bottom strip is reserved
# for the "Waiting for teacher..." text.
offset = (
    (W - img.width) // 2,
    max(2, (H - 22 - img.height) // 2),
)

canvas.paste(solid, offset, solid)

pixels = canvas.load()

out = []
out.append("// HCMUTE logo, 160x128 RGB565, generated by tools/convert_logo.py")
out.append("// White background + purple stroke logo, bottom strip reserved for text.")
out.append("#pragma once")
out.append("")
out.append("#include <Adafruit_GFX.h>")
out.append("")
out.append(f"#define LOGO_WIDTH {W}")
out.append(f"#define LOGO_HEIGHT {H}")
out.append("")
out.append("static const uint16_t LOGO_HCMUTE[LOGO_WIDTH * LOGO_HEIGHT] PROGMEM = {")

for y in range(H):
    row = []
    for x in range(W):
        r, g, b = pixels[x, y]

        rgb565 = (
            ((r & 0xF8) << 8)
            | ((g & 0xFC) << 3)
            | (b >> 3)
        )

        row.append(f"0x{rgb565:04X}")

    out.append("    " + ",".join(row) + ",")

out.append("};")
out.append("")

with open(DST, "w") as f:
    f.write("\n".join(out))

print(f"Wrote {DST} ({W}x{H}, {W*H} pixels)")

# Preview for quick visual check.
preview = canvas.resize((W * 3, H * 3), Image.NEAREST)
preview.save("assets/logo_preview.png")
print("Preview: assets/logo_preview.png")
